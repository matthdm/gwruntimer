// Shared git-revision helpers, `include!`d verbatim by each crate's `build.rs`
// and by xtask. Not a module of any crate -- keep it dependency-free and
// self-contained. Plain comments and outer attributes only: this text lands in
// the middle of another file, where inner attributes are illegal.

use std::path::PathBuf;
use std::process::Command;

/// Rough revision number, short hash, and whether the working tree is dirty.
///
/// Falls back to `(0, "unknown", false)` when git is unavailable (e.g. building
/// from a source tarball) so a missing git never fails the build.
#[allow(dead_code)]
fn git_info() -> (u32, String, bool) {
    let rev = git(&["rev-list", "--count", "HEAD"])
        .and_then(|s| s.parse::<u32>().ok())
        .unwrap_or(0);
    let hash = git(&["rev-parse", "--short", "HEAD"]).unwrap_or_else(|| "unknown".to_string());
    // `status --porcelain` prints nothing for a clean tree.
    let dirty = git(&["status", "--porcelain", "--untracked-files=no"])
        .map(|s| !s.is_empty())
        .unwrap_or(false);
    (rev, hash, dirty)
}

/// `r<rev>-<hash>`, with `-dirty` appended for uncommitted builds.
#[allow(dead_code)]
fn version_string(rev: u32, hash: &str, dirty: bool) -> String {
    format!("r{rev}-{hash}{}", if dirty { "-dirty" } else { "" })
}

#[allow(dead_code)]
fn git(args: &[&str]) -> Option<String> {
    let out = Command::new("git").args(args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    Some(String::from_utf8(out.stdout).ok()?.trim().to_string())
}

/// Writes `$OUT_DIR/version.rs` and tells cargo to re-run when HEAD moves.
/// Call this from `build.rs`.
#[allow(dead_code)]
fn emit_version_rs() {
    let (rev, hash, dirty) = git_info();
    let version = version_string(rev, &hash, dirty);

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR is set for build scripts");
    let dest = PathBuf::from(out_dir).join("version.rs");
    let contents = format!(
        "// @generated by build.rs -- do not edit.\n\
         /// Commit count on the current branch, used as a rough revision number.\n\
         pub const GIT_REVISION: u32 = {rev};\n\
         /// Shorthand hash of the commit this binary was built from.\n\
         pub const GIT_HASH: &str = {hash:?};\n\
         /// True when the working tree had uncommitted changes at build time.\n\
         pub const GIT_DIRTY: bool = {dirty};\n\
         /// `r<revision>-<hash>`, matching the name of the release zip.\n\
         pub const VERSION: &str = {version:?};\n"
    );
    std::fs::write(&dest, contents).expect("failed to write version.rs");

    emit_git_rerun_triggers();
    println!("cargo:rerun-if-changed=build.rs");
}

/// Re-run the build script when the checked-out commit changes. Only existing
/// paths are emitted -- a `rerun-if-changed` on a missing file makes cargo
/// re-run the script on every single build.
#[allow(dead_code)]
fn emit_git_rerun_triggers() {
    let Some(git_dir) = git(&["rev-parse", "--absolute-git-dir"]).map(PathBuf::from) else {
        return;
    };

    let mut watch = vec![git_dir.join("HEAD"), git_dir.join("packed-refs")];
    // The ref HEAD points at, e.g. `refs/heads/master`; absent while packed.
    if let Some(head_ref) = git(&["rev-parse", "--symbolic-full-name", "HEAD"]) {
        watch.push(git_dir.join(head_ref));
    }

    for path in watch {
        if path.exists() {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}
